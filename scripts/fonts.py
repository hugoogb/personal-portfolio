"""
Cuts the story's two variable fonts down to the weights the site uses and
writes them, with their @font-face rules, to src/assets/fonts and
src/styles/fonts.css. Both are committed; run this again after a fontsource
update or when the CSS starts using a weight outside WEIGHTS:
  python3 -m venv /private/tmp/claude-501/fonts
  /private/tmp/claude-501/fonts/bin/pip install fonttools==4.60.2 brotli==1.1.0
  /private/tmp/claude-501/fonts/bin/python scripts/fonts.py
  pnpm exec prettier --write src/styles/fonts.css
fonttools is not a project dependency; it comes from that scratch install.

A variable font carries its whole weight axis (100 to 900). Pinning the axis
to the weights in use makes the preloaded files a quarter smaller (spec 8).
Only latin and latin-ext ship: the site's text is English and Spanish.
"""

import re
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTSOURCE = ROOT / "node_modules/@fontsource-variable"
OUT = ROOT / "src/assets/fonts"
CSS = ROOT / "src/styles/fonts.css"

# family name in CSS -> (fontsource package, weight range in use)
WEIGHTS = {
    "Raleway": ("raleway", (400, 600)),
    "Hanken Grotesk": ("hanken-grotesk", (400, 900)),
}
SUBSETS = ["latin-ext", "latin"]


def unicode_range(package: str, subset: str) -> str:
    css = (FONTSOURCE / package / "wght.css").read_text()
    block = re.search(
        rf"/\* {package}-{subset}-wght-normal \*/.*?unicode-range: ([^;]+);", css, re.S
    )
    if not block:
        raise SystemExit(f"{package} has no {subset} subset in wght.css")
    return block.group(1)


OUT.mkdir(parents=True, exist_ok=True)
rules = [
    "/* Generated by scripts/fonts.py: do not edit by hand. */",
]
for family, (package, (low, high)) in WEIGHTS.items():
    for subset in SUBSETS:
        name = f"{package}-{subset}-wght-normal.woff2"
        font = TTFont(FONTSOURCE / package / "files" / name)
        instantiateVariableFont(font, {"wght": (low, high)}, inplace=True)
        font.flavor = "woff2"
        font.save(OUT / name)
        print(f"{name}: {(FONTSOURCE / package / 'files' / name).stat().st_size} -> {(OUT / name).stat().st_size}")
        rules.append(
            "\n".join(
                [
                    "",
                    "@font-face {",
                    f'  font-family: "{family}";',
                    "  font-style: normal;",
                    "  font-display: swap;",
                    f"  font-weight: {low} {high};",
                    f'  src: url("@/assets/fonts/{name}") format("woff2-variations");',
                    f"  unicode-range: {unicode_range(package, subset)};",
                    "}",
                ]
            )
        )
CSS.write_text("\n".join(rules) + "\n")
