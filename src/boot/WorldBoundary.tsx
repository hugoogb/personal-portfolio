import { Component, type ReactNode } from "react";

interface Props {
  onError: () => void;
  children: ReactNode;
}

export class WorldBoundary extends Component<Props, { failed: boolean }> {
  state = { failed: false };

  static getDerivedStateFromError() {
    return { failed: true };
  }

  componentDidCatch() {
    this.props.onError();
  }

  render() {
    return this.state.failed ? null : this.props.children;
  }
}
